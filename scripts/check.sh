#!/bin/sh
# Loads every plugin of this repository in a clean `zsh -f` through
# `zsh-tool init zsh` and checks its key aliases and functions.
#
# Usage: scripts/check.sh <path to the zsh-tool binary>
#
# A plugin passes when the checks succeed and nothing is written on stderr
# (neither by zsh-tool, e.g. an invalid manifest, nor by the plugin).

set -u

if [ $# -ne 1 ]; then
  echo "usage: $0 <zsh-tool binary>" >&2
  exit 2
fi
case $1 in
  /*) bin=$1 ;;
  *) bin=$PWD/$1 ;;
esac
if [ ! -x "$bin" ]; then
  echo "$0: $bin is not executable" >&2
  exit 2
fi

repo=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Checks run after `eval "$(zsh-tool init zsh)"`; each one prints a message
# on stdout and exits non-zero on failure. $WORK is a scratch directory and
# $WORK/bin comes first in $PATH. An optional pre_<plugin> snippet runs
# before the init script, for instance to create fake commands with `fake`.
# `rerun <code>` starts a fresh `zsh -f` in the same home that runs <code>,
# then the init script, and prints its stdout and stderr.
prelude='
fail() { print -r -- "$@"; exit 1 }
fake() {
  mkdir -p $WORK/bin
  print -r -- "#!/bin/sh"$'"'"'\n'"'"'"$2" > $WORK/bin/$1
  chmod +x $WORK/bin/$1
  rehash
}
rerun() {
  zsh -f -c "WORK=${(q)WORK}; path=(\$WORK/bin \$path); $1
eval \"\$(${(q)BIN} init zsh)\"; ${2-}" 2>&1
}
'
checks_git='
fail() { print -r -- "$@"; exit 1 }
[[ $aliases[gst] == "git status" ]] || fail "alias gst: $aliases[gst]"
[[ $aliases[gca!] == "git commit --verbose --all --amend" ]] || fail "alias gca!"
[[ $aliases[gbgd] == *"awk '"'"'{print \$1}'"'"'"* ]] || fail "alias gbgd: $aliases[gbgd]"
[[ -n $aliases[gfa] && -n $aliases[gpf] && -n $aliases[gpsupf] && -n $aliases[gsta] ]] || fail "version-dependent aliases"
for f in git_current_branch git_main_branch git_develop_branch ggp ggl gccd grename gbda; do
  (( $+functions[$f] )) || fail "function $f"
done
[[ $_comps[ggp] == _git ]] || fail "compdef ggp: $_comps[ggp]"
cd $WORK && git init -q -b trunk repo && cd repo || fail "git init"
git -c user.name=t -c user.email=t@t commit -q --allow-empty -m init || fail "git commit"
[[ $(git_current_branch) == trunk ]] || fail "git_current_branch: $(git_current_branch)"
[[ $(git_main_branch) == trunk ]] || fail "git_main_branch: $(git_main_branch)"
'

checks_sudo='
fail() { print -r -- "$@"; exit 1 }
(( $+functions[sudo-command-line] )) || fail "function sudo-command-line"
[[ -n ${(M)${(f)"$(zle -l)"}:#sudo-command-line} ]] || fail "widget sudo-command-line"
for keymap in emacs viins vicmd; do
  [[ $(bindkey -M $keymap "\e\e") == *sudo-command-line ]] || fail "bindkey $keymap"
done
'

checks_z='
fail() { print -r -- "$@"; exit 1 }
(( $+functions[zshz] )) || fail "function zshz"
[[ $aliases[z] == "zshz 2>&1" ]] || fail "alias z: $aliases[z]"
[[ $_comps[zshz] == _z ]] || fail "completion zshz: $_comps[zshz]"
mkdir -p $WORK/projects/zsh-tool-check
ZSHZ_DATA=$WORK/z-data
zshz --add $WORK/projects/zsh-tool-check
[[ $(zshz -e tool-check) == $WORK/projects/zsh-tool-check ]] || fail "z -e: $(zshz -e tool-check)"
'

checks_extract='
fail() { print -r -- "$@"; exit 1 }
(( $+functions[extract] )) || fail "function extract"
[[ $aliases[x] == extract ]] || fail "alias x: $aliases[x]"
[[ $_comps[extract] == _extract ]] || fail "completion extract: $_comps[extract]"
cd $WORK && mkdir src && print hello > src/a.txt && print world > src/b.txt && tar czf archive.tar.gz -C src a.txt b.txt || fail "tar"
extract archive.tar.gz > /dev/null 2>&1 || fail "extract failed"
[[ $(<archive/a.txt) == hello && $(<archive/b.txt) == world ]] || fail "extracted content"
'

checks_colored_man_pages='
fail() { print -r -- "$@"; exit 1 }
for f in colored man dman debman; do
  (( $+functions[$f] )) || fail "function $f"
done
[[ $(colored printenv LESS_TERMCAP_md) == $'"'"'\e[01;31m'"'"' ]] || fail "LESS_TERMCAP_md"
[[ $(colored printenv GROFF_NO_SGR) == 1 ]] || fail "GROFF_NO_SGR"
'

checks_history='
fail() { print -r -- "$@"; exit 1 }
[[ $aliases[h] == history && $aliases[hl] == "history | less" ]] || fail "alias h/hl"
[[ $aliases[hs] == "history | grep" && $aliases[hsi] == "history | grep -i" ]] || fail "alias hs/hsi"
'

pre_docker='
fake docker "case \$1 in
  --version) echo \"Docker version \${FAKE_DOCKER_VERSION:-24.0.2}, build cb74dfcd85\" ;;
  completion) echo \"#compdef docker\" ; echo \"# generated by docker completion\" ;;
esac"
'
checks_docker='
[[ $aliases[dps] == "docker ps" && $aliases[drm!] == "docker container rm -f" ]] || fail "alias dps/drm!"
[[ $aliases[dsta] == "docker stop \$(docker ps -q)" ]] || fail "alias dsta: $aliases[dsta]"
[[ $_comps[docker] == _docker ]] || fail "completion docker: $_comps[docker]"
wait_for() { local i; for i in {1..50}; do [[ -f $1 ]] && grep -q $2 $1 && return; sleep 0.1; done; fail "$1 does not contain $2" }
wait_for $ZSH_CACHE_DIR/completions/_docker "generated by docker completion"
rm $ZSH_CACHE_DIR/completions/_docker
out=$(rerun "export FAKE_DOCKER_VERSION=20.10.1") && [[ -z $out ]] || fail "docker 20: $out"
wait_for $ZSH_CACHE_DIR/completions/_docker "Felix Riedel"
rm $ZSH_CACHE_DIR/completions/_docker
out=$(rerun "zstyle :omz:plugins:docker legacy-completion yes") && [[ -z $out ]] || fail "legacy-completion: $out"
wait_for $ZSH_CACHE_DIR/completions/_docker "Felix Riedel"
'

checks_docker_compose='
[[ $aliases[dco] == "docker compose" && $aliases[dcupd] == "docker compose up -d" ]] || fail "alias dco without docker-compose: $aliases[dco]"
[[ $_comps[docker-compose] == _docker-compose ]] || fail "completion docker-compose: $_comps[docker-compose]"
fake docker-compose true
out=$(rerun "" "print -r -- \$aliases[dclF]") || fail "with docker-compose: $out"
[[ $out == "docker-compose logs -f --tail 0" ]] || fail "alias dclF with docker-compose: $out"
(( ! $+dccmd )) || fail "dccmd left behind"
'

checks_kubectl='
(( ! $+aliases[k] && ! $+functions[kj] )) || fail "aliases defined without kubectl"
fake kubectl "[ \"\$1\" = completion ] && echo \"#compdef kubectl generated\""
out=$(rerun "" "print -r -- \$aliases[k] \$aliases[kgp] \$_comps[kubectl] \$_comps[kj] \$+functions[kres]
sleep 0.5; cat \$ZSH_CACHE_DIR/completions/_kubectl") || fail "with kubectl: $out"
[[ $out == "kubectl kubectl get pods _kubectl _kj 1"$'"'"'\n'"'"'"#compdef kubectl generated" ]] || fail "with kubectl: $out"
'

pre_npm='
fake npm true
'
checks_npm='
[[ $aliases[npmg] == "npm i -g " && $aliases[npmE] == "PATH=\"\$(npm bin)\":\"\$PATH\"" ]] || fail "alias npmg/npmE: $aliases[npmE]"
[[ $_comps[npm] == _npm_completion ]] || fail "completion npm: $_comps[npm]"
[[ -n ${(M)${(f)"$(zle -l)"}:#npm_toggle_install_uninstall} ]] || fail "widget npm_toggle_install_uninstall"
[[ $(bindkey -M emacs "^[OQ^[OQ") == *npm_toggle_install_uninstall ]] || fail "bindkey F2 F2"
BUFFER="npm i left-pad" CURSOR=0
npm_toggle_install_uninstall
[[ $BUFFER == "npm uninstall left-pad" && $CURSOR == 8 ]] || fail "toggle: $BUFFER $CURSOR"
'

status=0
for dir in "$repo"/plugins/*/; do
  name=$(basename "$dir")
  var=checks_$(printf %s "$name" | tr -- - _)
  eval "checks=\${$var-}"
  eval "pre=\${pre_$(printf %s "$name" | tr -- - _)-}"
  if [ -z "$checks" ]; then
    echo "FAIL $name: no checks defined in $0"
    status=1
    continue
  fi

  home=$work/$name
  mkdir -p "$home/.config/zsh-tool" "$home/work"
  printf 'plugins = ["%s"]\n' "$name" > "$home/.config/zsh-tool/config.toml"
  script="WORK='$home/work'
BIN='$bin'
path=(\$WORK/bin \$path)
$prelude
$pre
eval \"\$('$bin' init zsh)\" || { print init failed; exit 90 }
$checks"
  out=$(env -i HOME="$home" PATH="$PATH" TERM=dumb ZSH_TOOL_HOME="$repo" \
    zsh -f -c "$script" 2> "$home/stderr")
  code=$?
  if [ $code -ne 0 ]; then
    echo "FAIL $name: $out"
    status=1
  elif [ -s "$home/stderr" ]; then
    echo "FAIL $name: unexpected stderr:"
    sed 's/^/  /' "$home/stderr"
    status=1
  else
    echo "ok   $name"
  fi
done
exit $status
